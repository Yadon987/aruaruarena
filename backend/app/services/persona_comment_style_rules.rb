# frozen_string_literal: true

module PersonaCommentStyleRules
  COMMENT_KEYWORD_REPLACEMENTS = {
    'hiroyuki' => {
      /共感度?/ => '再現性',
      /刺さる/ => '論点が通る',
      /あるある感/ => '解像度'
    }.freeze,
    'dewi' => {
      /共感度?/ => '品格',
      /刺さる/ => '華が立つ',
      /あるある感/ => '気品'
    }.freeze,
    'nakao' => {
      /共感度?/ => '余韻',
      /刺さる/ => '味が残る',
      /あるある感/ => '匂い立つ情景'
    }.freeze
  }.freeze

  COMMENT_LINE_REPLACEMENTS = {
    'hiroyuki' => {
      /共感(?:が|は)?強い(?:です)?/ => '再現性は高いって話です',
      /共感(?:が|は)?弱い(?:です)?/ => '再現性は低いですよね',
      /共感(?:が|は)?ある(?:です)?/ => '論点はズレてないって話です'
    }.freeze,
    'dewi' => {
      /共感(?:が|は)?強い(?:です)?/ => '気品のある着地ですわ',
      /共感(?:が|は)?弱い(?:です)?/ => '華が足りませんの',
      /共感(?:が|は)?ある(?:です)?/ => '気品が通っていますわ'
    }.freeze,
    'nakao' => {
      /共感(?:が|は)?強い(?:です)?/ => '余韻が深いかな',
      /共感(?:が|は)?弱い(?:です)?/ => '少し薄味だね',
      /共感(?:が|は)?ある(?:です)?/ => '味が残るかな',
      /共感(?:が|は)?残る(?:です)?/ => '余韻が残るかな'
    }.freeze
  }.freeze

  COMMENT_ENDINGS = {
    'hiroyuki' => {
      suffix: 'って話です',
      allowed: [
        /ですよね\z/,
        /よね\z/,
        /じゃないですか\z/,
        /って話です\z/,
        /なんですよね\z/,
        /だと思いますよ\z/,
        /ってところです\z/
      ].freeze
    }.freeze,
    'dewi' => {
      suffix: 'ですわ',
      allowed: [
        /ですわ\z/,
        /ですこと\z/,
        /ですの\z/,
        /よろしくてよ\z/,
        /ですわね\z/,
        /ますわ\z/,
        /ませんわ\z/,
        /ございませんわ\z/,
        /ありませんこと\z/
      ].freeze
    }.freeze,
    'nakao' => {
      suffix: 'だね',
      allowed: [
        /だね\z/,
        /だな\z/,
        /だよ\z/,
        /かな\z/,
        /じゃないか\z/,
        /だろうね\z/,
        /かもしれないね\z/,
        /ね\z/
      ].freeze
    }.freeze
  }.freeze
end
